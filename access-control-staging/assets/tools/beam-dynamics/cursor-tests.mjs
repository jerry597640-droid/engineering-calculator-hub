import assert from 'node:assert/strict';
import {build,statics} from './solver.js';
import {sectionFaces,snapStation} from './section-cursor.js';
const member={L:10,E:200,I:.0008,mass:800};
const config={spans:[member,member],supports:['pin','roller','roller'],mode:'static',mesh:12,selfWeight:false,axles:[{p:60,offset:0}],direction:1,factor:1,speed:60,step:.2,dt:.01,damping:2,tail:1,loads:[{type:'line',a:0,b:20,w1:10,w2:10},{type:'point',x:5,p:50}]};
const r=statics(build(config));
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,a+' vs '+b);
const support=sectionFaces(r,10,20);
near(support.left.M,-171.875);near(support.right.M,-171.875);
near(support.left.V,-92.1875);near(support.right.V,67.1875);near(support.right.D,0);
const point=sectionFaces(r,5,20);
near(point.left.V-point.right.V,50);near(point.left.M,point.right.M);
const left=sectionFaces(r,0,20),right=sectionFaces(r,20,20);
assert.equal(left.left,null);assert.equal(right.right,null);near(left.right.V,57.8125);near(right.left.V,-32.8125);
const moment=statics(build({...config,loads:[{type:'moment',x:3.6,p:72}]}));
const jump=sectionFaces(moment,3.6,20);near(jump.left.M-jump.right.M,72);
const stations=[0,5,10,15,20];
near(snapStation(9.99,20,.03,stations),10);near(snapStation(9.96,20,.03,stations),9.96);
near(snapStation(20.9,20,.1,stations),20);near(snapStation(-1,20,.1,stations),0);
console.log('Section cursor checks passed for support and concentrated-load jumps, beam ends, and snapping.');
